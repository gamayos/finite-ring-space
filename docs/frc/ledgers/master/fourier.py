def _shells(lo, hi):
    return [n for n in range(lo, hi) if n % 4 == 1 and arith.is_prime(n)]


def _scale_shift(p, pairs=None):
    """The clauses of C2 on the frame (p, drive(p)): cardinal values, additivity on the given pairs (all by default),
    periodicity, (F^[1])^κ = F, and the meridian covariance."""
    g, n, k = drive(p), p - 1, (p - 1) // 4
    W, J, F = transform(p, g)
    P = projectors(p, g)
    fam = {s: frft(p, g, s, P) for s in range(n)}
    FJ = matmul(F, J, p)
    ok = fam[0] == identity(n) and fam[k] == F and fam[2 * k] == J and fam[3 * k] == FJ
    ok &= matmul(FJ, F, p) == identity(n) and matmul(F, F, p) == J
    ok &= frft(p, g, n + 5, P) == fam[5 % n]
    pairs = pairs if pairs is not None else [(s, r) for s in range(n) for r in range(n)]
    ok &= all(matmul(fam[s], fam[r], p) == fam[(s + r) % n] for s, r in pairs)
    ok &= matpow(fam[1], k, p) == F
    ok &= all([x * pow(g, r, p) % p for x in meridian(p, g, k, m)] == meridian(p, g, k, m + r) for m in range(n) for r in range(n))
    return ok


