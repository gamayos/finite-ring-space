# block O: orientation is derived (00:C7)
# ħ^S = ±1 on a Carrier with S even; on a frame i = (g⁻¹)^κ, the conjugate g⁻¹ is a frame with quarter-turn −i,
# transform −F J and projectors Π_{ℓ+2} (Fourier.lean, orientation).
def _conjugate(p):
    g, n, k = drive(p), p - 1, (p - 1) // 4
    z = pow(g, -1, p)
    i = (-pow(g, k, p)) % p
    _, J, F = transform(p, g)
    _, _, Fz = transform(p, z)
    P, Pz = projectors(p, g), projectors(p, z)
    FJ = matmul(F, J, p)
    ok = pow(z, k, p) == i and element_order(z, p) == n and (-pow(z, k, p)) % p == (p - i) % p
    ok &= Fz == [[(-v) % p for v in row] for row in FJ]
    ok &= all(Pz[l] == P[(l + 2) % 4] for l in range(4))
    return ok


