# block M: every prime carries a frame (00:A13)
# every prime field has a primitive root, and its powers reach every nonzero residue (Drive.lean, exists_drive): the
# proof's construction is the product over the prime powers qᵉ ∥ p − 1 of a^((p−1)/qᵉ), a the least with a^((p−1)/q) ≠ 1.
@R.block("M", BLOCKS["M"])
def block_M():
    """Block M — every prime carries a frame (EXACT): M1–M3."""
    # 00:A13 (p00164)
    ok, det = True, []
    for Om, p in SHELLS:
        for q in (Om, p):
            g = drive(q)
            n = element_order(g, q)                                          # by iteration
            powers, y = set(), 1
            for _ in range(q - 1):
                powers.add(y); y = y * g % q
            ok &= n == q - 1 and arith.is_primitive_root(g, q) and powers == set(range(1, q))
        det.append(f"Ω={Om}: g={drive(Om)}; p={p}: g={drive(p)}")
    R.check("M1", "on the three Carriers and their Subjects: the drive g built by the proof's construction has order p − 1 (by iteration "
            "and by the factorisation of p − 1), and g⁰, …, g^(p−2) are all p − 1 nonzero residues", ok, "; ".join(det))
    # M2 every prime below SWEEP: the construction gives a primitive root, each factor z_q of order exactly qᵉ
    bad = []
    for p in _primes(2, SWEEP):
        n = p - 1
        for q, e in arith.factorize(n).items():
            a = next(a for a in range(1, p) if pow(a, n // q, p) != 1)
            z = pow(a, n // q ** e, p)
            if not (pow(z, q ** e, p) == 1 and pow(z, q ** (e - 1), p) != 1): bad.append((p, q))
        if arith.order(drive(p), p) != n: bad.append(p)
    R.check("M2", f"every prime p < {SWEEP}: for each qᵉ ∥ p − 1 the factor z_q = a^((p−1)/qᵉ) has order exactly qᵉ, and their product "
            "is a primitive root", not bad, f"{len(_primes(2, SWEEP))} primes; exceptions {bad[:5]}")
    # M3 every prime below 400: the elements of order p − 1, by iteration, number φ(p − 1), the drive among them
    bad = []
    for p in _primes(2, 400):
        prim = [x for x in range(1, p) if element_order(x, p) == p - 1]
        if len(prim) != arith.phi(p - 1) or drive(p) not in prim: bad.append(p)
    R.check("M3", "every prime p < 400: the elements of order p − 1, found by iteration, number φ(p − 1) and include the drive", not bad,
            f"{len(_primes(2, 400))} primes; exceptions {bad}")


