# block I: completeness is primality (00:A11)
# for q ≥ 2, every ideal of Z/q holding a nonzero residue holds every residue iff q is prime (Foundation.lean,
# isPrime_iff_complete): forward by the Fermat inverse a^(q−2), backward by the annihilator of a zero divisor.
@R.block("I", BLOCKS["I"])
def block_I():
    """Block I — completeness is primality (EXACT): I1, I2."""
    # I1 the forward construction on the Carriers and the Subjects: a^(q−2) inverts every nonzero a
    ok, det = True, []
    for Om, p in SHELLS[:2]:
        for q in (Om, p):
            ok &= all(a * pow(a, q - 2, q) % q == 1 for a in range(1, q))
        det.append(f"q={Om} and q={p}: a·a^(q−2) = 1 for every a ≠ 0")
    Om = SHELLS[2][0]
    ok &= all(a * pow(a, Om - 2, Om) % Om == 1 for a in range(1, 200001))
    det.append(f"q={Om}: for a < 200 001")
    R.check("I1", "on the Carriers and their Subjects: the Fermat inverse a^(q−2) of every nonzero a, so 1 lies in every ideal holding "
            "a, and with it every residue", ok, "; ".join(det))
    # 00:A11 (p00162)
    bad, det = [], []
    for q in range(2, 260):
        comp, prime, zd = is_complete(q), arith.is_prime(q), zero_divisors(q)
        if not (comp == prime == (not zd)): bad.append(q)
        if not prime:
            a, b = zd[0]
            ann = [x for x in range(q) if x * b % q == 0]                       # the annihilator of b, an ideal holding a
            if not (a in ann and 1 not in ann and principal_ideal(a, q) != list(range(q))): bad.append((q, "annihilator"))
    R.check("I2", "every q in [2, 260): Z/q has no proper nonzero ideal (every residue's ideal holds 1, by search) iff q is prime iff "
            "no zero divisors; for composite q the annihilator of a zero divisor b is a proper ideal holding a ≠ 0", not bad,
            f"258 moduli, {sum(1 for q in range(2, 260) if arith.is_prime(q))} prime; exceptions {bad[:5]}")


