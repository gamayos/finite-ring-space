# block Q: counting closes by return (00:A6)
# on q ≥ 2 points the successor x ↦ x + 1 has no fixed point, returns after exactly the multiples of q steps and
# reaches every point (Foundation.lean, successor_cycle).
@R.block("Q", BLOCKS["Q"])
def block_Q():
    """Block Q — counting closes by return (EXACT): Q1, Q2."""
    # 00:A6 (p00188)
    ok, det = True, []
    for Om, p in SHELLS:
        for q in (Om, p):
            orb = successor_orbit(q, 0)
            ok &= len(orb) == q and sorted(orb) == list(range(q)) and all((x + 1) % q != x for x in (0, 1, q - 1))
        det.append(f"Ω={Om}: one cycle of {Om}; p={p}: one cycle of {p}")
    R.check("Q1", "on the three Carriers and their Subjects: the orbit of 0 under x ↦ x + 1 returns after exactly q steps and "
            "visits every point; x + 1 ≠ x", ok, "; ".join(det))
    # Q2 every q in [2, 400): the k-th iterate fixes a point iff q | k (k < 3q), every orbit is all of [0, q), no fixed point
    bad = []
    for q in range(2, 400):
        for x in (0, q // 2, q - 1):
            y, ret = x, []
            for k in range(1, 3 * q):
                y = (y + 1) % q
                if y == x: ret.append(k)
            if ret != [q, 2 * q] or sorted(successor_orbit(q, x)) != list(range(q)): bad.append((q, x))
        if any((x + 1) % q == x for x in range(q)): bad.append((q, "fixed point"))
    R.check("Q2", "every q in [2, 400) and x ∈ {0, ⌊q/2⌋, q−1}: C_q^k x = x for 0 < k < 3q exactly at k = q, 2q (by iteration); every "
            "orbit is all of [0, q); no point is fixed", not bad, f"exceptions {bad[:5]}")


