# block U: a bounded observer is a proper part (00:A4)
# an observer with o < Ω states holds no injective encoding of the Ω points: every reading identifies two distinct points
# (Foundation.lean, observer_part; the pigeonhole).
@R.block("U", BLOCKS["U"])
def block_U():
    """Block U — a bounded observer is a proper part (EXACT): U1–U3."""
    # 00:A4 (p00159)
    total, bad = 0, []
    for n in range(1, SMALL + 1):
        for o in range(n):
            for rho in itertools.product(range(o), repeat=n):
                total += 1
                if collision(lambda x: rho[x], n) is None: bad.append((n, o, rho))
    R.check("U1", f"every total of n ≤ {SMALL} points and every observer of o < n states: each of the o^n readings identifies two "
            "distinct points (exhaustive)", not bad, f"{total} readings; injective ones {bad[:3]}")
    # U2 the bound is sharp: o = n states admit an injective reading
    ok = all(collision(lambda x: x, n) is None for n in range(1, SMALL + 1)) and all(
        all(collision(lambda x: rho[x], n) is None for rho in itertools.permutations(range(n))) for n in range(1, SMALL + 1))
    R.check("U2", f"the bound is sharp: for every n ≤ {SMALL}, an observer of n states reads the n points injectively (each of the n! "
            "bijections, the identity among them)", ok, "o < n forces a collision, o = n does not")
    # U3 on the three Carriers, an observer of Ω − 1 states: three readings, each with two distinct points found by search
    ok, det = True, []
    for Om, p in SHELLS:
        o = Om - 1
        readings = {"x mod (Ω−1)": lambda x: x % o, "min(x, Ω−2)": lambda x: min(x, o - 1),
                    "p x mod (Ω−1)": lambda x: p * x % o}
        for name, rho in readings.items():
            c = collision(rho, Om)
            ok &= c is not None and c[0] != c[1] and rho(c[0]) == rho(c[1]) and all(0 <= rho(x) < o for x in (c[0], c[1]))
        det.append(f"Ω={Om}: x mod (Ω−1) identifies {collision(readings['x mod (Ω−1)'], Om)}")
    R.check("U3", "on the three Carriers, an observer of Ω − 1 states: the readings x mod (Ω−1), min(x, Ω−2) and p·x mod (Ω−1) each "
            "identify two distinct points, found by search", ok, "; ".join(det))


