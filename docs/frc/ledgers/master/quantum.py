import random
import sys
from math import gcd, lcm

from frc import arith
from frc.registry import Registry
from frc.quantum import joint_period, orbits, offset, reach, root_of_unity, character_sums

# ---- generated by ci/make_ledgers.py from docs/00-ledger.json; edit the ledger, not this table ----
BLOCK = "F"
KEYS = {"F1": "p00059", "F2": "p00060", "F4": "p00062", "F5": "p00063", "F6": "p00064", "F7": "p00177"}       # every row of the block: its label and its accession key
LEAN = {"F2": "core"}       # the rows with a Lean declaration: the libraries whose key files prove them
