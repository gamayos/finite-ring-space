# block O: the quarter-turn is the odd member of the ±√−1 pair (00:C14)
# e^{jπ} := (g^j)^{j·2κ} = (−1)^j; the roots h, −h of −1 have representatives of opposite parity, so e^{hπ} = −1 exactly
# on the odd one; the inverse drive is a frame with quarter-turn −i; every frame is g^u with u odd, its quarter-turn i
# when u ≡ 1 (mod 4) and −i when u ≡ 3, and the parity names the class (Subject.lean, quarter_turn_odd).
def _odd_member(p, g):
    k = (p - 1) // 4
    i = (-pow(g, k, p)) % p
    roots = quarter_turns(p)
    ok = all(euler(g, j, p) == (1 if j % 2 == 0 else p - 1) for j in range(p))
    ok &= len(roots) == 2 and roots[0] % 2 != roots[1] % 2
    ok &= all((euler(g, h, p) == p - 1) == (h % 2 == 1) for h in roots)
    gi = pow(g, -1, p)
    ok &= element_order(gi, p) == p - 1 and (-pow(gi, k, p)) % p == (p - i) % p
    for g2 in frames(p):
        u = chirality(g, g2, p)
        i2 = (-pow(g2, k, p)) % p
        ok &= u is not None and u % 2 == 1 and (i2 == i) == (u % 4 == 1) and (i2 == (p - i) % p) == (u % 4 == 3)
        ok &= ((i2 % 2) == (i % 2)) == (u % 4 == 1)
    return ok


