def squares(p):
    """Every square x² mod p, 0 included, by search: a set."""
    return {x * x % p for x in range(p)}


def _shells(lo, hi):
    """The primes p = 4κ + 1 in [lo, hi)."""
    return [n for n in range(lo, hi) if n % 4 == 1 and arith.is_prime(n)]


def _web(p, g):
    """The frame's web on (p, g): 2π ≡ −1, g^π ≡ −1, −π·2 ≡ 1, i² ≡ −1 (C1)."""
    k = (p - 1) // 4
    pi, i = 2 * k, (-pow(g, k, p)) % p
    return 2 * pi % p == p - 1 and pow(g, pi, p) == p - 1 and (-pi) * 2 % p == 1 and i * i % p == p - 1


