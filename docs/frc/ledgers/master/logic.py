# block Q: Gödel vacuous over a finite structure (00:Z1)
# a finite structure carries no injective successor missing an element, so it interprets no Q; its first-order theory is
# decided by exhaustive evaluation, complete and consistent (Logic.lean: no_finite_successor, fin_theory_decidable,
# fin_theory_complete, fin_theory_consistent).
@R.block("Q", BLOCKS["Q"])
def block_Q():
    """Block Q — Gödel vacuous over a finite structure (EXACT): Q1–Q3."""
    # 00:Z1 (p00186)
    rng = random.Random(1)
    bad, n_checked = [], 0
    for m in SIZES:
        for t in range(3):
            M = random_structure(rng, m)
            for _ in range(FORMULAS // 3):
                k = rng.randrange(1, 3)
                phi = random_formula(rng, 5, k)
                T = table(M, phi, k)
                for a in product(range(m), repeat=k):
                    v, w = fval(M, a, phi), fval(M, a, ("neg", phi))
                    n_checked += 1
                    if v != (a in T) or v == w: bad.append((m, phi, a))
    succ = [n for n in range(1, MAPS + 1) if successor_counterexample(n) is not None]
    R.check("Q1", f"random structures on 1–4 elements, {FORMULAS} random formulas each size: the exhaustive evaluation agrees with "
            "the satisfying tables built bottom-up, and exactly one of φ, ¬φ holds; every map [0, n) → [0, n), n ≤ "
            f"{MAPS}: none is injective and misses an element", not bad and not succ,
            f"{n_checked} evaluations; exceptions {bad[:2]}; successor counterexamples at n = {succ}")
    # Q2 the shells 𝔽_p: Q's axiom "0 is no successor" is false, and the successor is injective
    bad = []
    for p in (5, 13, 17, 29):
        M = _shell_structure(p)
        q1 = ("all", ("all", ("neg", ("conj", ("rel", 0, (1, 0)), ("rel", 1, (0,))))))    # ∀x ∀y ¬(S x = y ∧ y = 0)
        inj = ("all", ("all", ("all", ("neg", ("conj", ("conj", ("rel", 0, (2, 0)), ("rel", 0, (1, 0))), ("neg", ("eq", 2, 1)))))))
        if fval(M, (), q1) or not fval(M, (), inj) or table(M, q1, 0) or not table(M, inj, 0): bad.append(p)
    R.check("Q2", "the shells 5, 13, 17 and 29 with the successor x ↦ x + 1 as a relation: the successor is injective and Q's axiom "
            "∀x S x ≠ 0 is false, by both evaluators: the shell interprets no Q through its successor", not bad,
            f"exceptions {bad}")
    # Q3 sentences of the shell 𝔽_13 decided: 2 000 random sentences, each true or false, never both
    M = _shell_structure(13)
    bad, true = [], 0
    for _ in range(2000):
        phi = ("all", random_formula(rng, 4, 1))
        v = fval(M, (), phi)
        true += v
        if v == fval(M, (), ("neg", phi)) or v != (() in table(M, phi, 0)): bad.append(phi)
    R.check("Q3", "the shell 𝔽₁₃ with its successor, its zero and its doubling: 2 000 random sentences, each decided by both "
            "evaluators, exactly one of σ, ¬σ true", not bad, f"{true} true, {2000 - true} false")


