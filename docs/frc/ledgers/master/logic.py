# block W: no compression (00:Z9)
# (i) per symbol: over M_2 the graph of an injective map on M_2^N (N = 1, 2) is a relation in 2N coordinates whose truth
# depends on all of them, so every formula of length <= 9 that defines it mentions all 2N variables (25:F2's instances;
# the core's template_size and no_template give the general accounting: the diagonal formula needs more than N symbols).
# (ii) in digit form: k*(a, d) by the search of F6 (frc.diagonal.k_star, the Lean's kstar), the digit bound
# k* < a^(floor(d/3)+4) and t(a, d) = d k* < a^(d-1) over the fifteen pairs (a, d) the general bound leaves (a <= 5,
# 5 <= d <= 12 with 6 d a^(floor(d/3)+1) > a^(d-1)), and k* = 0 below five digits.  (iii) the window: Int_J(x) defines
# {0, ..., 2^J - 1} on the small prime fields, model-checked as written; the chart's bound of Ω (00:A7, between 1.32 and
# 1.33 x 10^123) has 82 base-32 digits, so one element of the instance's field, at 1,024 digits, holds more than every
# element of Ω — the comparison in digit counts, no numeral above Ω formed.
@R.block("W", BLOCKS["W"])
def block_W():
    """Block W — no compression (EXACT): W1."""
    # 00:Z9 (p00187)
    ok = True; det = []
    # (i) the graphs of the injective maps on M_2^N, N = 1, 2, among the formulas of length <= 9 over M_2 in 2N variables
    for N in (1, 2):
        V = 2 * N; T, _ = formulas_M2(V, 9)
        pts = list(product(range(2), repeat=N))
        def bit(assign):                                   # the assignment (x, y) of 2N bits as the index of the truth table
            return sum(b << i for i, b in enumerate(assign))
        graphs = set()
        for f in product(range(len(pts)), repeat=len(pts)):
            if len(set(f)) != len(pts): continue           # injective
            mask = 0
            for i, x in enumerate(pts):
                mask |= 1 << bit(x + pts[f[i]])
            graphs.add(mask)
        full = (1 << V) - 1; n_def = 0; n_short = 0
        for length, fs in T.items():
            for tab, free, text in fs:
                if tab in graphs:
                    n_def += 1
                    ok &= free == full                     # every defining formula mentions all 2N variables
                    ok &= len(text) > N                    # and is longer than the N-tuple it would be coded by
                if free != full and tab in graphs: n_short += 1
        ok &= len(graphs) == {1: 2, 2: 24}[N] and n_def > 0 and n_short == 0
        det.append(f"N={N}: {len(graphs)} injective graphs, {n_def} defining formulas of length <= 9, all in {V} variables")
    # (ii) k* and t in digit form over the fifteen pairs the general bound leaves, and k* = 0 below five digits
    pairs = [(a, d) for a in range(2, 6) for d in range(5, 13) if 6 * d * a ** (d // 3 + 1) > a ** (d - 1)]
    ok &= len(pairs) == 15
    for a, d in pairs:
        k = k_star(a, d); t = threshold(a, d)
        ok &= 0 < k < a ** (d // 3 + 4) and t == d * k and t < a ** (d - 1)
        ok &= 3 * name_cost(k, a) < d * k                  # the admitted k* passes lambda's count
    ok &= all(k_star(a, d) == 0 for a in range(2, 6) for d in range(1, 5))
    det.append("fifteen pairs: " + ", ".join(f"({a},{d}) k*={k_star(a, d)} t={threshold(a, d)}<{a ** (d - 1)}" for a, d in pairs[:4]) + ", ...")
    # (iii) the decoders on small prime fields, and the window's digit count against the chart's bound of Ω
    dd = dense(); g = dd.Gen(); V, Ev = dd.V, dd.Ev; n_dec = 0
    for p in dd.primes_upto(31):
        J = 0
        while (1 << J) <= p:
            f = g.Int(V("x20"), J); e = Ev(p)
            ok &= {x for x in range(p) if e.ev(f, {"x20": x})} == set(range(1 << J)); n_dec += 1; J += 1
    lo, hi = 132 * 10 ** 121, 133 * 10 ** 121                # the chart's bracket of Ω (00:A7), as integers
    digits = len(_digits32(hi))                                # base-32 digits of the upper bound
    ok &= 32 ** 81 <= lo and hi < 32 ** 82 and digits == 82 and 82 < 1024
    det.append(f"{n_dec} (p, J) decoders; Ω's chart bound has {digits} base-32 digits, the instance 1024 per element")
    R.check("W1", "No compression: over M_2 every formula of length <= 9 defining the graph of an injective map on M_2^N (N = 1, 2) "
            "mentions all 2N variables and exceeds N symbols; k*(a, d) in digit form with t = d k* < a^(d-1) over the fifteen "
            "pairs the general bound leaves, k* = 0 below five digits; Int_J decodes {0, ..., 2^J - 1} on the prime fields up to 31; "
            "the chart's bound of Ω has 82 base-32 digits against the instance's 1024 per element", ok, "; ".join(det))


def _digits32(n):
    """The base-32 digits of n, most significant first (the count the window is compared by)."""
    out = []
    while n: out.append(n % 32); n //= 32
    return out[::-1]


