# block A: the square classes and the nonexistence theorem (3:B1, B2, B3)
# Section 2 of the paper: the two square classes of F_p^x with −1 a square (p ≡ 1 mod 4); no s ∈ F_p has s² = ν for a
# nonsquare ν, and for s ≠ 0 every coefficient of −s²t² + x² + y² + z² is a square (thm:nonexistence; s = 0 gives a
# degenerate form); the absorption lemma by rescaling, no root of a_0 needed (lem:square-class-absorption); the class of
# ν as the datum, canonically ν = g.
@R.block("A", BLOCK["A"])
def block_A():
    """Block A — the square classes and the nonexistence theorem (EXACT): A1–A4."""
    # A1 the square classes, −1 a square, s² and −s² squares, no causal square root (3:B2)
    ok = True
    for p in SWEEP + (1549,):
        sq = bytearray(p)
        for s in range(1, p): sq[s * s % p] = 1
        ok &= sum(sq) == (p - 1) // 2 and sq[p - 1] == 1
        ok &= all(sq[(-s * s) % p] for s in range(1, p))
        g = drive(p); ok &= sq[g] == 0                                           # no s with s² = g: g is no square
    # 3:B2 (p03006)
    R.check("A1", "F_p^x splits into two classes of (p-1)/2; -1, s^2 and -s^2 are squares (s != 0); no s with s^2 in N", ok,
            "the 21 shells below 200 and 𝔽₁₅₄₉")

    # A2 the absorption lemma: coefficients in one class => Q = a_0 sum (w_j X_j)^2 with w_j^2 = a_j/a_0;
    #    no root of a_0 is used: a_0 in N has none (3:B3)
    ok = True; det = []
    for p in SMALL:
        S, N = squares(p), nonsquares(p)
        root = {}
        for w in range(1, p): root.setdefault(w * w % p, w)
        for cls in (S, N):
            for a0 in cls:
                for a1 in cls:
                    for a2 in cls:
                        for a3 in cls:
                            a = (a0, a1, a2, a3); inv0 = pow(a0, -1, p)
                            ws = [root.get(ai * inv0 % p) for ai in a]
                            ok &= all(w is not None for w in ws) and all((a0 * w * w) % p == ai for w, ai in zip(ws, a))
        ok &= all(nu not in root for nu in N)
        det.append(f"p={p}: {len(S)**4 + len(N)**4} one-class tuples")
    # 3:B3 (p03007)
    R.check("A2", "one square class => Q equivalent to a_0 (sum of squares) by w_j^2 = a_j/a_0; no root of a_0 exists for a_0 in N", ok, "; ".join(det))

    # A3 the class is the datum: every primitive root is a nonsquare; Q_nu depends on nu only through its class,
    #    Q_{nu w^2}(t, x, y, z) = Q_nu(w t, x, y, z) (3:B1)
    ok = True
    for p in SWEEP:
        ok &= all(not is_square(g, p) for g in generators(p))
        nu = drive(p)
        for w in range(1, p):
            nu2 = nu * w * w % p
            ok &= all(Q((-nu2, 1, 1, 1), (t, x, 1, 2), p) == Q((-nu, 1, 1, 1), (w * t, x, 1, 2), p) for t in range(p) for x in (0, 1, 5))
    ok &= not is_square(drive(1549), 1549) and drive(13) == drive(173) == drive(1549) == 2
    R.check("A3", "every primitive root g is a nonsquare (nu = g canonical); Q_nu depends on nu only through its class", ok,
            "the 21 shells below 200; the drive 2 on 𝔽₁₃, 𝔽₁₇₃, 𝔽₁₅₄₉")

    # A4 s in F_p^x gives a Euclidean form; s = 0 a degenerate one (3:B2)
    ok = True
    for p in SWEEP + (1549,):
        for s in ((1, 2, 3) if p > 200 else range(1, p)):
            ok &= isotropic_count(((-s * s) % p, 1, 1, 1), p) == p ** 3 + p * p - p
        ok &= isotropic_count((0, 1, 1, 1), p) != p ** 3 + p * p - p
    R.check("A4", "-s^2 t^2 + x^2 + y^2 + z^2 (s != 0) has p^3 + p^2 - p zeros: the Euclidean (hyperbolic) type; s = 0 degenerate", ok)

