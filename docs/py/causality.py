                            if (a * d - b * c) % p == 1 and all(Q(coeffs, ((a * t + b * x) % p, (c * t + d * x) % p), p) == Q(coeffs, (t, x), p) for t, x in ((1, 0), (0, 1), (1, 1))):
                                n += 1; shape &= (d == a and c == coeff * b % p)
