def two_squares(p):
    """p = a^2 + b^2 with 0 < a <= b (Fermat, p = 1 mod 4)."""
    for a in range(1, math.isqrt(p) + 1):
        b = math.isqrt(p - a * a)
        if a <= b and a * a + b * b == p: return a, b


def ghost_radius(p, nu):
    """The least R such that some integer point with every |coordinate| <= R has x^2+y^2+z^2 - nu t^2 in pZ, nonzero."""
    R = 0
    while True:
        R += 1
        sq = [i * i for i in range(R + 1)]
        s3 = {a + b + c for a in sq for b in sq for c in sq}
        if any((s - nu * u) % p == 0 and s != nu * u for s in s3 for u in sq): return R


