# the curvature K(v) = 1 - deg(v)/2 + sum over the faces at v of 1/|f|, in exact fractions.
from collections import deque
from fractions import Fraction


def completion(p):
    """(n, pi, vertices, faces, adjacency) of the spherical completion of S_p."""
    n = p - 1; pi = n // 2
    V = ["N"] + [(a, m) for a in range(1, pi) for m in range(n)] + ["S"]
    F = [["N", (1, m), (1, (m + 1) % n)] for m in range(n)]
    F += [[(a, m), (a + 1, m), (a + 1, (m + 1) % n), (a, (m + 1) % n)] for a in range(1, pi - 1) for m in range(n)]
    F += [[(pi - 1, m), "S", (pi - 1, (m + 1) % n)] for m in range(n)]
