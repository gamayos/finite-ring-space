# block K: the shell theorem (00:Z10)
# the finite zeta vanishes on the nonterminal modes; every vector expands in the power modes; the scale-shift has the
# modes as eigenvectors with (p − 1)-th roots of unity as eigenvalues and fixes n·[n | r] points; every readout lies on
# Tr = 1 (Horizon.lean: zero_slot, mode_expansion, shift_power_character, eigenphase, shift_trace, readout_on_line,
# readout_slot_index).
@R.block("K", BLOCKS["K"])
def block_K():
    """Block K — the shell theorem (EXACT): K1–K3."""
    # 00:Z10 (p20043)
    rng = random.Random(10)
    bad = []
    for p in _shells(5, SWEEP):
        g = drive(p)
        vs = [_prime_vector(p, g), [rng.randrange(p) for _ in range(p - 1)]]
        if not _shell_theorem(p, vs): bad.append(p)
    R.check("K1", f"every prime p = 4κ + 1 below {SWEEP} with its drive: Z(k) = 0 for 0 < k < p − 1 and Z(p − 1) = −1; the prime "
            "vector and a random vector expand exactly in the power modes with the Lean proof's coefficients; (g^r x)^k = "
            "(g^r)^k x^k with (g^r)^k an (p − 1)-th root of unity; g^r fixes p − 1 points when (p − 1) | r and none otherwise; "
            "every readout 2⁻¹ + θη has trace 1; no slot index is 0 or −1", not bad,
            f"{len(_shells(5, SWEEP))} shells; exceptions {bad}")
    # K2 the Subjects 13, 173 and 1373: the expansion of every basis vector at 13, of the prime vector at all three
    ok, det = True, []
    for p in SUBJECTS:
        g, n = drive(p), p - 1
        vs = [_prime_vector(p, g)] + ([[1 if j == i else 0 for j in range(n)] for i in range(n)] if p == 13 else [])
        ok &= _shell_theorem(p, vs)
        det.append(f"p={p}: {sum(vs[0])} prime residues")
    R.check("K2", "the Subjects 13, 173 and 1373: the clauses of K1, with every basis vector at 13 (the modes span the cycle)", ok,
            "; ".join(det))
    # K3 a second method: the coefficients solve the Vandermonde system x_j^k (Gaussian elimination mod p)
    bad = []
    for p in (13, 17, 29, 37):
        g, n = drive(p), p - 1
        v = [rng.randrange(p) for _ in range(n)]
        A = [[pow(pow(g, j, p), e, p) for e in range(n)] + [v[j]] for j in range(n)]
        for col in range(n):                                    # Gauss-Jordan mod p
            piv = next(r for r in range(col, n) if A[r][col] % p)
            A[col], A[piv] = A[piv], A[col]
            inv = pow(A[col][col], -1, p)
            A[col] = [a * inv % p for a in A[col]]
            for r in range(n):
                if r != col and A[r][col]:
                    f = A[r][col]; A[r] = [(a - f * b) % p for a, b in zip(A[r], A[col])]
        if [A[e][n] for e in range(n)] != mode_coeffs(p, g, v): bad.append(p)
    R.check("K3", "p = 13, 17, 29, 37: the coefficients of a random vector by Gauss–Jordan elimination on the Vandermonde system "
            "equal the Lean proof's c_k = −Σ v_l g^((n−l)k)", not bad, f"exceptions {bad}")


