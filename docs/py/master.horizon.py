def _shells(lo, hi):
    return [n for n in range(lo, hi) if n % 4 == 1 and arith.is_prime(n)]


def _prime_vector(p, g):
    """20-rh's prime vector on the cycle: v_j = 1 when the residue g^j, read in [1, p), is a prime, else 0."""
    return [1 if arith.is_prime(pow(g, j, p)) else 0 for j in range(p - 1)]


def _shell_theorem(p, vectors):
    """The clauses of Z10 on the frame (p, drive(p)): the finite zeta, the expansion of each vector, the eigen-relation
    and its root of unity, the fixed-point count of every shift, the readouts on Tr = 1 and the slot indices."""
    g, n, k = drive(p), p - 1, (p - 1) // 4
    ok = all(zeta(p, e) == 0 for e in range(1, n)) and zeta(p, n) == p - 1
    for v in vectors:
        c = mode_coeffs(p, g, v)
        ok &= all(expand(p, g, c, j) == v[j] % p for j in range(n))
    rs = range(0, 2 * n + 1) if n <= 60 else list(range(0, 8)) + [n, 2 * n, n + 1]
    for r in rs:
        lam = [pow(pow(g, r, p), e, p) for e in range(n)]
        ok &= all(pow(shift(p, g, r, x), e, p) == lam[e] * pow(x, e, p) % p for x in range(1, p, max(1, p // 40)) for e in range(0, n, max(1, n // 12)))
        ok &= all(pow(l, n, p) == 1 for l in lam)
        ok &= len(fixed_points(p, g, r)) == (n if r % n == 0 else 0)
    half = (2 * k + 1) % p
    ok &= 2 * half % p == 1 and half == (-2 * k) % p
    ok &= all(trace(p, readout(p, t)) == 1 and readout(p, t)[0] == half for t in range(p))
    ok &= all((-pow(g, e, p)) % p not in (0, p - 1) for e in range(1, n))
    return ok


