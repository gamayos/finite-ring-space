def _within(x, centre, tol): return abs(Q(x) - Q(centre)) < Q(tol)


# ------------------------------------------------------------------------------------------------------------
# block F: flavour, structure (00:G15)
@R.block("F", BLOCKS["F"])
def block_F():
    """Block F — flavour, structure (EXACT): F1, F2."""
    # F1 the seesaw fixes Q_ν = 2/3: with M_R = c m_D the seesaw collapses to c² det(m_D) m_Dᵀ (20 random rational
    #    circulants), the transpose circulant has the Dirac eigenvalues, and the signed Koide identity holds for them
    ok = True
    for _ in range(20):
        mD = FL.random_circ(RNG); c = Q(RNG.randint(1, 9), RNG.randint(1, 5))
        ok &= FL.transpose_fixed_point(c, mD) and FL.seesaw_closure(mD, FL.random_circ(RNG))[0]
        a, b = FL.QOmega(Q(RNG.randint(1, 9))), FL.QOmega(Q(RNG.randint(-9, 9), RNG.randint(1, 5)), Q(RNG.randint(-9, 9), RNG.randint(1, 5)))
        ok &= FL.transpose_eigen(a, b, b.conj())
        lam = [l.x for l in FL.eigenvalues(a, b, b.conj())]
        ok &= (3 * sum(x * x for x in lam) == 2 * sum(lam) ** 2) == (2 * b.norm() == a.x * a.x)
    for p in SHELLS:                                                          # the Dirac amplitude: Q = 2/3 exactly on the shells
        S = FL.Shell(p); ok &= S.koide_point(1, Q(1, 2))[1] == S.frac(Q(2, 3))
    # 00:G15 (p00080)
    R.check("F1", "the seesaw fixes Q_ν = 2/3: with M_R = c m_D (the 126 alignment) the seesaw m_D·adj(M_R)·m_Dᵀ is c² det(m_D) m_Dᵀ, "
            "whose eigenvalues are the Dirac eigenvalues λ_{−k} (20 random rational circulants), so the colourless Dirac amplitude "
            "2N(b) = a², Q = 2/3 exact on F_17, F_53, F_89, is the neutrinos' (the transpose fixed point)", ok,
            "the seesaw of circulants is circulant; the amplitude is preserved, the phase reset")

    # F2 the role-ladder ordering and the mixing's reduction: the ladder of roles closes on F_13, F_53, F_157, F_421 (no
    #    fifth role; the three generative roles the generations), the role depths (2, 1, 0) give the texture exponents,
    #    and the trimaximal column is the protected one
    ok = True
    for p in (13, 53, 157, 421):
        g, n = arith.primitive_root(p), p - 1
        ok &= all(LD.tower(g, j, p)[0] == LD.tower(g, j, p)[1] for j in range(n)) and any(pow(g, j, p) >= n for j in range(n))
    down, up, Ed, Eu = FL.texture_exponents(); v, u, notprop = FL.protected_column()
    ok &= down == (4, 2, 0) and up == (8, 4, 0) and v and u and notprop
    R.check("F2", "the role-ladder ordering and the mixing's reduction: the tower g^(g^j) is read modulo p − 1 on F_13, F_53, F_157, "
            "F_421 (the ladder closes, three generative roles), the depths (2, 1, 0) give the exponents (4, 2, 0) and (8, 4, 0) of "
            "the role-depth texture, and the shift fixes the trimaximal column (1, 1, 1) alone", ok, "the mixing reduces to the "
            "texture, the lopsided entry and the protected column; the phases stay Ω-hard (Z6)")


# ------------------------------------------------------------------------------------------------------------
# block R: flavour, exact ratios (00:G17)
@R.block("R", BLOCKS["R"])
def block_R():
    """Block R — flavour, exact ratios (EXACT): R1, R2."""
    # R1 Koide 2/3 and the norms: Q = 2/3 ⟺ 2N(b) = a² and N(1 − i) = 2, N(1 − ω) = 3 on the shells; the colour count 3;
    #    the magic matrix trimaximal with J² = 1/108 in Q(ω) and 4(−νh²) = 3 in F_p
    ok = all(FL.norms_two_three(p) and FL.jarlskog_framed(p) for p in SHELLS)
    for p in SHELLS:
        S = FL.Shell(p); ok &= S.koide_point(1, Q(1, 2))[1] == S.frac(Q(2, 3)) and S.koide_point(1, Q(3, 4))[1] == S.frac(Q(5, 6))
    dc, ec, nine = FL.colour_count(); tri, q, J2 = FL.magic_matrix()
    ok &= (dc, ec, nine) == (3, 1, 9) and tri and q and J2 == Q(1, 108)
    # 00:G17 (p00179)
    R.check("R1", "the exact ratios: Q = 2/3 exactly at 2N(b) = a² and Q = 5/6 at 4N(b) = 3a² on F_17, F_53, F_89; the squared "
            "amplitudes N(1 − i) = 2 and N(1 − ω) = 3; the Georgi–Jarlskog factor the colour count 3 against 1 on the sixteen; the "
            "magic matrix trimaximal with J² = 1/108 in Q(ω) and 4(−νh²) = 3 in F_p", ok,
            "the split and non-split norms, the colour triplet, the cube-root phase")

    # R2 the λ-texture from role depths and the locks: the exponents (4, 2, 0), (8, 4, 0); the lock relations as trace
    #    identities on every unit of F_{p²}
    down, up, Ed, Eu = FL.texture_exponents()
    ok = down == (4, 2, 0) and up == (8, 4, 0) and all(FL.trace_relations(p) for p in SHELLS)
    R.check("R2", "the λ-texture from the role depths (2, 1, 0): the exponents (4, 2, 0) and (8, 4, 0); the charged sectors' lock "
            "1 : 1/2 : 1/3 as the trace relations T(z²) = T(z)² − 2, T(z³) = T(z)³ − 3T(z) of a unit, exhaustive on F_{17²}, F_{53²}, "
            "F_{89²}", ok, "c_ℓ = 2c_d² − 1 = 4c_u³ − 3c_u between the cube invariants")


# ------------------------------------------------------------------------------------------------------------
# block T: flavour, targets (00:P3)
@R.block("T", BLOCKS["T"])
def block_T():
    """Block T — flavour, targets (CHART): T1."""
    gj, msd, btau = CFL.gj_double_ratio(); tot, m2, m3 = CFL.neutrino_floor(); dl, dd, du, dup = CFL.phase_lock()
