#!/usr/bin/env python3
"""make_master.py — the master ledger's predicate declarations, named (run from lean/, the lake package root; 8 November 2026).

A paper's rows have their named declarations in the paper's module (`FRC.Rh.incompleteness_of_observation`, written by
make_predicates.py). The master ledger (00-master/predicates/index.md, published as docs/00-ledger.json and, for its block P,
docs/predictions.json) has no paper module: its rows' Lean declarations are the keys themselves, `FRC.Ledger.p<key>` in the
core's key files and `FRC.LedgerML.p<key>` in Mathlib's, and the key files are keyed by design. This writes the master's
module in each library, so that every bound master row has a declaration named by its declared name (`name:` in index.md,
`lean_name` in the JSONs; one name per key across the ledgers that carry it):

    FrcCore/Master.lean       namespace FRC.Master — theorem <name> : <the key's statement> := @FRC.Ledger.p<key>
    FrcMathlib/Master.lean    namespace FRC.Master — theorem <name> : <the key's statement> := @FRC.LedgerML.p<key>

A row is bound to the core when a master block file names its proofs (frc/ledgers/master/<theme>.py, PROOFS) and to Mathlib
when the file binds its chart clauses (CHART); a row bound in both libraries (00:P4) has a declaration in each. The
statement is the key file's (make_keys.py --typed); a key still in the def form gives a def-form alias, stated at the next
typed pass of the keys. The docstring opens `00:A4 (p00197) — …`, as make_predicates.py writes it, so the site reads the
declaration as the row's predicate and anchors the key beside the name. Each module imports the key files it aliases and
nothing else; the library's root imports the module.

    python3 make_master.py --docs ../docs            # (re)write both modules (and the roots' import lines)
    python3 make_master.py --docs ../docs --check    # exit 1 if a module or a root is stale
"""
import argparse, ast, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
import make_predicates as MP                                                     # noqa: E402

LIBS = ("FrcCore", "FrcMathlib")
KEYNS = MP.KEYNS                                                                  # FrcCore: FRC.Ledger, FrcMathlib: FRC.LedgerML
BOUND_BY = {"PROOFS": "FrcCore", "CHART": "FrcMathlib"}
HEAD = "-- Ledger predicates of 00-ledger (generated by make_master.py from docs/00-ledger.json, docs/predictions.json and the key files; edit the ledger, not this file)"
END = MP.END

DOC = {
    "FrcCore": """/-!
# FrcCore.Master — the master ledger's predicate declarations (8 November 2026)

One declaration per master row whose proofs a block file names (`frc/ledgers/master/<theme>.py`, PROOFS), `FRC.Master.<name>`,
named by the row's declared name (`name:` in `00-master/predicates/index.md`), each the alias of the row's key `FRC.Ledger.p<key>`
in the core's key files, which `make_keys.py` writes from the same bindings; the key stands in the docstring. Generated by
`make_master.py`; the theorems live in the themes, the keys in `Keys/`. No axioms (`check_core_axioms.py`).
-/""",
    "FrcMathlib": """/-!
# FrcMathlib.Master — the master ledger's predicate declarations on Mathlib (8 November 2026)

One declaration per master row whose chart clauses a block file binds to Mathlib theorems (`frc/ledgers/master/<theme>.py`,
CHART), `FRC.Master.<name>`, named by the row's declared name (`name:` in `00-master/predicates/index.md`), each the alias of the
row's key `FRC.LedgerML.p<key>` in Mathlib's key files, which `make_keys.py` writes from the same bindings; the key stands in
the docstring. Generated by `make_master.py`; the theorems live in the chart theme, the keys in `Keys/`.
-/""",
}


def master_rows(docs):
    """label -> {key, name, statement, block} over docs/00-ledger.json and the master's prediction rows of docs/predictions.json
    (block P, listed on the Predictions tab only), with the master's block order."""
    d = json.loads((docs / "00-ledger.json").read_text(encoding="utf-8"))
    order = list(d["blocks"]) if isinstance(d["blocks"], dict) else [b.get("letter") or b.get("block") for b in d["blocks"]]
    rows = {r["label"]: {"key": r["key"], "name": r.get("lean_name"), "statement": r["statement"], "block": r["block"]} for r in d["rows"]}
    pj = docs / "predictions.json"
    if pj.exists():
        for r in json.loads(pj.read_text(encoding="utf-8"))["rows"]:
            if r.get("paper") == "00" and r["label"] not in rows:
                rows[r["label"]] = {"key": r["key"], "name": r.get("lean_name"), "statement": r["predicate"], "block": re.match(r"[A-Z]+", r["label"]).group(0)}
    return rows, order


def bindings():
    """label -> the libraries a block file binds it to (PROOFS: the core, CHART: Mathlib), with the file's name."""
    out, d = {}, ROOT.parent / "frc" / "ledgers" / "master"
    for f in sorted(d.glob("*.py")) if d.exists() else []:
        if f.name == "__init__.py": continue
        text = f.read_text(encoding="utf-8")
        for table, lib in BOUND_BY.items():
            m = re.search(rf"^{table} = (\{{.*?^\}})", text, re.M | re.S)
            for label in (ast.literal_eval(m.group(1)) if m else {}): out.setdefault(label, {})[lib] = f.stem
    return out


def module_text(lib, rows, order, bound):
    """The module for one library: the header, the key-file imports, the declarations in the master's order; None when the
    library binds no master row."""
    labels = [l for l in rows if lib in bound.get(l, {})]
    if not labels: return None, []
    rank = {b: i for i, b in enumerate(order)}
    labels.sort(key=lambda l: (rank.get(rows[l]["block"], len(rank)), int(re.sub(r"\D", "", l))))
    keyed, stated = MP.keyed(lib), MP.key_statements(lib)
    problems, decls, imports = [], [], set()
    for l in labels:
        r = rows[l]; key, name = r["key"], r["name"]
        if not name: problems.append(f"00:{l} ({key}) is bound to {lib} by {bound[l][lib]}.py and has no declared name — name it in index.md and rebuild the site"); continue
        if not re.fullmatch(r"[a-z][a-z0-9_]*", name): problems.append(f"00:{l}: the declared name {name!r} is not lower snake case"); continue
        if key not in keyed: problems.append(f"00:{l} ({key}, {name}) is bound to {lib} but no key file of {lib} declares the key — run make_keys.py"); continue
        imports.add(keyed[key])
        doc = f"/-- 00:{l} ({key}) — {MP.doc_text(r['statement'])} -/"
        term = f"@{KEYNS[lib]}.{key}"
        if key in stated: decls.append(f"{doc}\ntheorem {name} : {stated[key]} :=\n  {term}")
        else: decls.append(f"set_option linter.defProp false in\n{doc}\ndef {name} := {term}")
    if problems: return problems, []
    text = "".join(f"import {lib}.{m}\n" for m in sorted(imports)) + "\n" + DOC[lib] + "\n\nnamespace FRC.Master\n\n" + HEAD + "\n" + "\n".join(decls) + f"\n{END}\n\nend FRC.Master\n"
    return text, labels


def root_text(lib):
    """The library's root with `import <lib>.Master` as its last import line."""
    p = ROOT / f"{lib}.lean"; src = p.read_text(encoding="utf-8")
    if re.search(rf"^import {lib}\.Master\s*$", src, re.M): return src
    lines = src.split("\n"); k = max(i for i, l in enumerate(lines) if l.startswith("import "))
    lines.insert(k + 1, f"import {lib}.Master")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--docs", required=True); ap.add_argument("--check", action="store_true")
    a = ap.parse_args(); docs = Path(a.docs)
    rows, order = master_rows(docs); bound = bindings(); stale = []
    for lib in LIBS:
        text, labels = module_text(lib, rows, order, bound)
        if text is None: continue
        if isinstance(text, list): sys.exit(f"make_master.py: {lib}:\n  " + "\n  ".join(text))
        for p, new in ((ROOT / lib / "Master.lean", text), (ROOT / f"{lib}.lean", root_text(lib))):
            old = p.read_text(encoding="utf-8") if p.exists() else None; rel = p.relative_to(ROOT)
            if old == new: print(f"{rel}: current") if not a.check else None
            elif a.check: stale.append(str(rel))
            else:
                p.write_text(new, encoding="utf-8")
                print(f"{rel}: " + (f"{len(labels)} declarations written" if p.name == "Master.lean" else "import written"))
    if a.check:
        if stale: sys.exit("master module stale: " + ", ".join(stale) + " — run make_master.py")
        print("master modules current")


if __name__ == "__main__":
    main()
