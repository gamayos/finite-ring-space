# ---- R: the roles and the closure ----------------------------------------------------------------------------------------
@R.block("R", BLOCK["R"])
def block_R():
    """Block R — closure_pnp.py T1, T2, T4 (EXACT): the tower reduction (26:G2), the phase formula (26:G3), the four
    roles' counts (26:G4), the bijective and the compressive power maps (26:G5)."""
    # R1: a tower exponent is read modulo P-1; the index map m -> k m; the orbit of iterated exponentiation closes
    ok, det = True, []
    for p in (13, 101, 1009):
        g, n = g_of(p), p - 1
        ok &= all(LD.tower(g, j, p) == (pow(g, pow(g, j, p), p), pow(g, pow(g, j, p) % n, p)) for j in range(n))   # against pow
        ok &= all(pow(g, pow(g, j, p), p) == pow(g, pow(g, j, p) % n, p) for j in range(n))                         # the identity itself
        ok &= any(pow(g, j, p) >= n for j in range(n))                                                               # the reduction acts
        ok &= all(pow(pow(g, m, p), k, p) == pow(g, k * m % n, p) for m in range(n) for k in (2, 3, 5, 7))
