# ---- L: the longitudinal turn --------------------------------------------------------------------------------------------
@R.block("L", BLOCK["L"])
def block_L():
    """Block L — longitudinal_turn.py (EXACT): the characters as eigenvectors of the scale shift (26:B3), the dilation
    generator (26:B4, CHART), the Gauss-sum telescoping and modulus (26:B5), the exponential bijection (26:E10, F10)."""
    # L1: the scale shift x ↦ g x on the units, the characters χ_ν(g^t) = g^{νt} its eigenvectors, eigenvalue g^ν, distinct
    ok, det = True, []
    for p in TURN:
        g, n = g_of(p), p - 1
        lams = set()
        for nu in range(n):
            v = [pow(g, nu * t % n, p) for t in range(n)]
            lam = pow(g, nu, p)
            ok &= all(v[(t + 1) % n] == lam * v[t] % p for t in range(n))       # (S v)_t = v_{t+1} = λ v_t
            lams.add(lam)
        ok &= len(lams) == n
        fixed = [len(HZ.fixed_points(p, g, r)) for r in (0, 1, n // 2, n, n + 1)]
        ok &= fixed == [n, 0, 0, n, 0]
        det.append(f"F_{p}: {n} eigenvectors, {len(lams)} distinct eigenvalues, fixed points {fixed}")
    # 26:B3 (p26009)
    R.check("L1", "the characters are eigenvectors of the scale shift x -> g x with the (P-1)-th roots of unity as distinct eigenvalues; the shift fixes every unit when (P-1) | r and none otherwise",
            ok, "; ".join(det))

    # L2: Ĥ = -i(x d/dx + 1/2) on x^s with s = -1/2 + i ν: by the power rule x d/dx x^s = s x^s, so Ĥ x^s = -i(s + 1/2) x^s,
    # and -i(s + 1/2) = -i(i ν) = ν. Computed in Q(i)[ν]: a number is (re, im) with coefficients polynomials in ν (lists).
    def padd(a, b): return [x + y for x, y in zip(a + [0] * (len(b) - len(a)), b + [0] * (len(a) - len(b)))]
    def pmul(a, b):
        out = [Fr(0)] * (len(a) + len(b) - 1)
        for i, x in enumerate(a):
            for j, y in enumerate(b): out[i + j] += x * y
        return out
    def cmul(z, w):                                    # (re, im) × (re, im)
        return padd(pmul(z[0], w[0]), [-c for c in pmul(z[1], w[1])]), padd(pmul(z[0], w[1]), pmul(z[1], w[0]))
    def strip(a):
        while a and a[-1] == 0: a = a[:-1]
        return a
    s = ([Fr(-1, 2)], [Fr(0), Fr(1)])                  # s = -1/2 + i ν
    coef = cmul(([Fr(0)], [Fr(-1)]), (padd(s[0], [Fr(1, 2)]), s[1]))   # -i (s + 1/2)
    nu = ([Fr(0), Fr(1)], [])
    ok = strip(coef[0]) == strip(nu[0]) and strip(coef[1]) == strip(nu[1])
    # 26:B4 (p26010)
    R.check("L2", "the dilation generator H = -i(x d/dx + 1/2) has x^(-1/2 + i nu) as eigenfunction of eigenvalue nu: the eigenvalue's coefficient -i(s + 1/2) with s = -1/2 + i nu is nu, computed in Q(i)[nu] (the power rule x d/dx x^s = s x^s is the chart's)",
            ok, "-i(s + 1/2) = nu exactly; the power rule x d/dx x^s = s x^s is the chart's", kind="CHART")

    # L3: the telescoping: t ↦ tc permutes the units; Σ_{t≠0} ψ(tc) = -1 (c ≠ 0) or P-1 (c = 0) in Z[ζ_P]; Σ_u χ(u) = 0 for χ ≠ 1
    ok, det = True, []
    for p in TURN:
        g, n = g_of(p), p - 1
        ok &= all(LD.mul_perm(c, p) for c in range(1, p))
        Cp = Cyclotomic(p)
        ok &= all(LD.ramanujan(p, c, Cp) == Cp.const(-1) for c in range(1, p)) and LD.ramanujan(p, 0, Cp) == Cp.const(n)
        Cn = Cyclotomic(n)
        ok &= all(Cn.sum(Cn.zeta(nu * t % n) for t in range(n)) == Cn.zero for nu in range(1, n))
        ok &= Cn.sum(Cn.zeta(0) for t in range(n)) == Cn.const(n)
        det.append(f"F_{p}: every c permutes the units; the additive sums -1 and {n}; the {n - 1} nontrivial character sums vanish")
    R.check("L3", "the telescoping of the Gauss sum: multiplication by a unit permutes the units, the additive character sum over the units is -1 for c != 0 and P-1 for c = 0, every nontrivial multiplicative character sums to 0",
            ok, "; ".join(det))

    # L4: |g(χ_ν)|² = P exactly in Z[ζ_{P(P-1)}]
    ok, det = True, []
    for p, nus in ((13, (1, 2, 5, 11)), (17, (1, 3, 8))):
        g, n = g_of(p), p - 1
        C = Cyclotomic(p * n)
        res = [LD.gauss_norm(p, g, nu, C) == C.const(p) for nu in nus]
        ok &= all(res)
        det.append(f"F_{p}: g(chi)·conj g(chi) = {p} in Z[zeta_{p * n}] for nu in {nus}")
    # 26:B5 (p26011)
    R.check("L4", "the Gauss sum of a nontrivial character against the additive character has modulus squared P, computed exactly in the cyclotomic ring Z[zeta_{P(P-1)}]",
            ok, "; ".join(det))

    # L5: exp t ↦ g^t is a bijection C_{P-1} → the units
    ok, det = True, []
    for p in TURN:
        g, n = g_of(p), p - 1
        img = [pow(g, t, p) for t in range(n)]
        ok &= sorted(img) == list(range(1, p))
        det.append(f"F_{p}: the {n} powers of {g} are the units")
    R.check("L5", "the exponential t -> g^t is a bijection of the index cycle onto the units", ok, "; ".join(det))


# ---- H: the horizon arithmetic on the bracket --------------------------------------------------------------------------
@R.block("H", BLOCK["H"])
def block_H():
    """Block H (CHART on the bracket): the family P^2 < Ω has at most 205 bits, a 204-bit decision table exceeds the
    absolute horizon Ω^{1/4} (26:C2); the three scales on the worked carriers (EXACT)."""
    lo, hi = CH.omega_bracket()
    flo, fhi = lo.numerator // lo.denominator, hi.numerator // hi.denominator     # the integer floors of the ends
    s_lo, s_hi = isqrt(flo), isqrt(fhi)                                            # ⌊√Ω⌋ at the two ends
    q_lo, q_hi = isqrt(s_lo), isqrt(s_hi)                                          # ⌊Ω^{1/4}⌋
    ok = (flo.bit_length() == 410 == fhi.bit_length() and 2 ** 204 < s_lo and s_hi < 2 ** 205
          and 2 ** 102 < q_lo and q_hi < 2 ** 103 and 2 ** 204 > q_hi and s_lo.bit_length() == 205 == s_hi.bit_length()
          and q_lo.bit_length() == 103 == q_hi.bit_length())
    # 26:C2 (p26013)
    R.check("H1", "on the certified bracket of Omega = 4S + 1: 2^204 < sqrt(Omega) < 2^205, so the family P^2 < Omega has shells of at most 205 bits; 2^102 < Omega^(1/4) < 2^103, so a 204-bit decision table (2^204 entries) lies beyond the absolute horizon and below sqrt(Omega)",
            ok, f"the bracket's ends have bit length {flo.bit_length()}; sqrt(Omega) has {s_lo.bit_length()} bits ({len(str(s_lo))} digits), Omega^(1/4) has {q_lo.bit_length()} bits ({len(str(q_lo))} digits); no numeral beyond the bracket's ends formed", kind="CHART")

    # H2: the three scales on the worked carriers: P^2 < Omega (the family), the descent's count 2(isqrt(P-1)+1) < sqrt(P)·2 + 2 ≤ Omega^{1/4}, P < sqrt(Omega)
    ok, det = True, []
    for p in (13, 101, 1009, 10007, 1000003, 100000007):
        m = isqrt(p - 1) + 1
        ok &= p * p < flo and m * m >= p - 1 and (m - 1) ** 2 <= p - 1 and 2 * m < q_lo and p < s_lo
        det.append(f"P={p}: m={m}, 2m={2 * m}")
    R.check("H2", "the three scales at the worked carriers: P^2 < Omega (the family), the giant-step bound 2(isqrt(P-1)+1) is far below Omega^(1/4), and P itself below sqrt(Omega)",
            ok, "; ".join(det))


# ---- C: the localising chart -----------------------------------------------------------------------------------------------
@R.block("C", BLOCK["C"])
def block_C():
    """Block C — chart_localization.py (EXACT): the recentring chart (26:E8), the index as counting distance and the
    bijection (26:E10), the ascent as the coordinate map and the descent as its inverse (26:F10)."""
    # C1: for every index m the translation recentre(n, m, ·) carries m to 1, one step from the origin 0, and permutes the indices
    ok, det = True, []
    for p in (13, 101, 1009):
        g, n = g_of(p), p - 1
        for m in range(n):
            ok &= pow(g, LD.recentre(n, m, m), p) == g == pow(g, 0, p) * g % p
            ok &= sorted(LD.recentre(n, m, j) for j in range(n)) == list(range(n))
        det.append(f"F_{p}: every m carried to 1 by a permutation of the {n} indices")
    # 26:E8 (p26025)
    R.check("C1", "existence is free: for every witness index m the translated chart recentre(n, m, .) places m one counting step from the origin and is a bijection of the index cycle",
            ok, "; ".join(det))

    # C2: the counting distance of a unit is its index 1..P-1 (the suite's convention: g^k reached after k steps, 1 = g^(P-1) after P-1); a bijection, mean P/2, maximum P-1 = 2^ell - O(1)
    ok, det = True, []
    for p in LOCAL:
        g, n = g_of(p), p - 1
        dist, x = {}, 1
        for k in range(1, p):
            x = x * g % p
            dist.setdefault(x, k)
        vals = sorted(dist.values())
        ell = (p - 1).bit_length()                        # ⌈log₂ P⌉ for P not a power of two
        mean = Fr(sum(vals), n)
        ok &= vals == list(range(1, p)) and mean == Fr(p, 2) and max(vals) == n and 2 ** (ell - 1) < n < 2 ** ell
        det.append(f"F_{p}: bijection onto 1..{n}, mean {mean}, max {n}, ell={ell} bits")
    # 26:E10 (p26027)
    R.check("C2", "the counting distance of a unit along the orbit of g is its index: a bijection onto 1..P-1 with mean P/2 and maximum P-1, between 2^(ell-1) and 2^ell for ell the bit length",
            ok, "; ".join(det))

    # C3: a_P(j) = g^j is the coordinate map C_{P-1} -> units and d_P = dlog its inverse, agreeing with the index table
    ok, det = True, []
    for p in (13, 17, 53, 101):
        g, n = g_of(p), p - 1
        table = LD.index_table(g, p)
        ok &= sorted(table) == list(range(1, p)) and sorted(table.values()) == list(range(n))
        ok &= all(pow(g, m, p) == x for x, m in table.items())                  # each index reproduces its unit
        ok &= all(LD.dlog(g, pow(g, j, p), p) == j for j in range(n)) and all(pow(g, LD.dlog(g, x, p), p) == x for x in range(1, p))
        ok &= all(LD.dlog(g, pow(g, j, p), p) == j % n for j in (n, n + 1, 2 * n + 3))   # an exponent beyond the cycle reads modulo n
        det.append(f"F_{p}: a_P a bijection, dlog its two-sided inverse on all {n} units")
    # 26:F10 (p26038)
    R.check("C3", "the ascent a_P: j -> g^j is a bijection of the index cycle onto the units and the descent dlog is its inverse on every unit",
            ok, "; ".join(det))


# ---- A: the ascent -----------------------------------------------------------------------------------------------------------
@R.block("A", BLOCK["A"])
def block_A():
    """Block A — closure_pnp.py T2 (EXACT): square-and-multiply within 2ℓ multiplications (26:F2)."""
    ok, det = True, []
    def exact_counts(e):                                 # the counts the two scans must report, from the bit pattern of e alone
        b, ones = len(bin(e)) - 2 if e > 0 else 0, bin(e).count("1")
        return b - 1 + ones if e > 0 else 0, b + ones  # right to left (the last squaring skipped), left to right
    for p in CARRIERS:
        g, ell = g_of(p), p.bit_length()
        for e in (p - 2, p // 3):
            v, ops = LD.sqmul(g, e, p); v2, ops2 = LD.sqmul_ltr(g, e, p)
            ok &= v == pow(g, e, p) == v2 and (ops, ops2) == exact_counts(e) and ops <= ops2 <= 2 * ell and ops2 <= 2 * LD.bits(e)
        det.append(f"P={p}: ell={ell}, {LD.sqmul(g, p - 2, p)[1]} and {LD.sqmul(g, p // 3, p)[1]} multiplications at e=P-2, P/3 (bound {2 * ell})")
    for e in range(1 << 10):
        v, ops = LD.sqmul(2, e, 13); v2, ops2 = LD.sqmul_ltr(2, e, 13)
        ok &= v == pow(2, e, 13) == v2 and (ops, ops2) == exact_counts(e) and ops2 <= 2 * LD.bits(e)
        ok &= (LD.bits(e) == 0 if e == 0 else (1 << (LD.bits(e) - 1)) <= e < (1 << LD.bits(e)))   # bits(e) against the powers of two
    # 26:F2 (p26030)
    R.check("A1", "square-and-multiply computes g^j in at most 2·bits(j) modular multiplications, hence at most 2·ell for j < P, the counts those of the bit pattern (right to left with the last squaring skipped: bits(j) - 1 + popcount(j); left to right: bits(j) + popcount(j)): on the three carriers at j = P-2 and P/3, and on F_13 for every j < 2^10",
            ok, "; ".join(det) + "; F_13: every e < 1024 within 2·bits(e)")


# ---- D: the descent ------------------------------------------------------------------------------------------------------
@R.block("D", BLOCK["D"])
def block_D():
    """Block D — closure_pnp.py T3 (EXACT): baby-step–giant-step recovers the index with the stated counts (26:F3); the
    bound (26:F3); the ratio table (26:G4)."""
    ok, det = True, []
    counts = {}
    for p in CARRIERS:
        g, n = g_of(p), p - 1
        m = isqrt(n) + 1
        x = p // 3
        res = LD.bsgs(g, pow(g, x, p), p)
        i, j, giant = res
        ok &= pow(g, j + m * i, p) == pow(g, x, p) and (j + m * i) % n == x and giant <= m and j < m
        counts[p] = (m, giant, m + giant)
        det.append(f"P={p}: m={m}, {giant} giant steps, {m + giant} operations")
    ok &= [counts[p][2] for p in CARRIERS] == [134, 1334, 13334]
    for p, m in ((13, 4), (101, 10)):
        g = g_of(p)
        ok &= all(LD.descends(g, pow(g, x, p), p, m) for x in range(p - 1))
        res = [LD.bsgs(g, pow(g, x, p), p, m) for x in range(p - 1)]
        ok &= all(r is not None and r[1] < m and (r[1] + m * r[0]) % (p - 1) == x for x, r in enumerate(res))   # the pair itself
    ok &= not LD.descends(g_of(101), pow(g_of(101), 50, 101), 101, 3) and LD.descends(g_of(101), pow(g_of(101), 8, 101), 101, 3)   # m = 3 reaches 8, not 50
    # 26:F3 (p26031)
    R.check("D1", "baby-step-giant-step with m = isqrt(P-1)+1 recovers the index of g^x: on the three carriers at x = P/3 with 134, 1334, 13334 operations (the m baby steps and the giant steps), and on F_13 (m = 4) and F_101 (m = 10) for every target",
            ok, "; ".join(det) + "; F_13 and F_101: every index recovered")

    # D2: the bound: m^2 >= P-1 and the operation count m + i <= 2m = 2(isqrt(P-1)+1); every target on F_101 within the bound
    ok, det = True, []
    for p in (101, 1009, 10007):
        g, n = g_of(p), p - 1
        m = isqrt(n) + 1
        worst = 0
        for x in range(n):
            i, j, giant = LD.bsgs(g, pow(g, x, p), p)
            ok &= giant < m and (j + m * i) % n == x
            worst = max(worst, m + giant)
        ok &= m * m >= n and worst <= 2 * m
        det.append(f"F_{p}: m={m}, worst {worst} <= {2 * m}")
    R.check("D2", "the descent's bound: with m^2 >= P-1 every index is recovered within 2m = 2(isqrt(P-1)+1) operations, checked on every target of F_101, F_1009 and F_10007",
            ok, "; ".join(det))

    # D3: the ratio table of prop:invlast, descent over ascent at the three carriers (the data the paper quotes)
    pairs = []
    for p in CARRIERS:
        g = g_of(p)
        asc = LD.sqmul(g, p // 3, p)[1]
