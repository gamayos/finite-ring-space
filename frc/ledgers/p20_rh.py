def next_prime(n):
    """The least prime above n."""
    n += 1
    while not arith.is_prime(n): n += 1
    return n


def carrier_of(p):
    """The Carrier chart of A11: the least prime ≡ 1 (mod 4) above p²."""
    om = next_prime(p * p)
    while om % 4 != 1: om = next_prime(om)
    return om


def dual(v, p):
    """The dual of a vector v on F_p^× (v[x] for x = 1..p−1): v̂(k) = Σ_x v(x) x^k for k = 0..p−2, in F_p."""
    return [sum(v[x] * pow(x, k, p) for x in range(1, p)) % p for k in range(p - 1)]


def random_vectors(p, count, seed):
    """The package's random vectors on F_p^×: python's generator at the seed (the same stream in the package)."""
    rng = random.Random(seed)
    return [[0] + [rng.randrange(p) for _ in range(p - 1)] for _ in range(count)]


def matmul_mod(A, B, p):
    n = len(A)
    return [[sum(A[i][k] * B[k][j] for k in range(n)) % p for j in range(n)] for i in range(n)]


