# block C: the primordial tilt (00:L8)
# n_s − 1 = −π²/ln Ω at ln Ω = 283.5: −0.0348, +0.07σ from −0.0351 ± 0.0042; the count ½ ln Ω excluded at 8.2σ
# (Chart.lean: tilt_ledger).
@R.block("C", BLOCKS["C"])
def block_C():
    """Block C — the primordial tilt (CHART): C1, C2."""
    # 00:L8 (p00148)
    mag = C.tilt_bracket()
    fit, err = C.TILT_FIT
    dev = ((-fit - mag[1]) / err, (-fit - mag[0]) / err)
    half = C.tilt_bracket(C.LN_OMEGA / 2)
    exc = ((half[0] + fit) / err, (half[1] + fit) / err)
    ok = _inside(mag, Q("0.03481"), Q("0.03482")) and _inside(dev, Q("0.068"), Q("0.069")) and _inside(exc, Q("8.2"), Q("8.25"))
    R.check("C1", "in rational arithmetic: at ln Ω = 283.5, 0.03481 < π²/ln Ω < 0.03482 (n_s − 1 = −0.0348); the deviation from "
            "−0.0351 ± 0.0042 between +0.068σ and +0.069σ; the count ½ ln Ω off by between 8.2σ and 8.25σ", ok,
            f"π²/ln Ω in ({C.show(mag[0], '.7f')}, {C.show(mag[1], '.7f')})", kind="CHART")
    # C2 floating point; 21-gravity's own reading at ln Ω = 281 (122 ln 10) gives −0.0351 and 8.4σ, its chart
    s1, s2 = C.sigma(C.tilt(), C.TILT_FIT), C.sigma(C.tilt(C.LN_OMEGA / 2), C.TILT_FIT)
    s3 = C.sigma(C.tilt(Q(281) / 2), C.TILT_FIT)
    ok = (_near(C.tilt(), Q("-0.0348"), Q("0.00005")) and _near(s1, Q("0.07"), Q("0.005")) and _near(s2, Q("-8.2"), Q("0.05"))
          and _near(C.tilt(Q(281)), Q("-0.0351"), Q("0.00005")) and _near(s3, Q("-8.4"), Q("0.05")))
    R.check("C2", "floating point: −π²/283.5 = −0.0348, +0.07σ, ½ ln Ω at −8.2σ; at 21-gravity's ln Ω = 281 the same form "
            "gives −0.0351 and −8.4σ (the paper's reading)", ok, f"tilt {C.tilt():.5f}, {s1:+.3f}σ, half {s2:+.2f}σ; at 281: {s3:+.2f}σ",
            kind="CHART")


# ------------------------------------------------------------------------------------------------------------
# block D: the running floor (00:P1)
# a₀(z) = cH(z)/2π and v⁴ = G M a₀ give a₀(z)/a₀(0) = H(z)/H(0) and (v(z)/v(0))⁴ = H(z)/H(0): the zero-point evolves as
# E(z)^{1/4} (Chart.lean: running_floor).
@R.block("D", BLOCKS["D"])
def block_D():
    """Block D — the running floor (CHART): D1, D2."""
    # 00:P1 (p00133)
    rng = random.Random(31)
    p_lo, p_hi = C.pi_bracket()
    bad = 0
    for _ in range(300):
        pi_ = p_lo + (p_hi - p_lo) * Q(rng.randrange(1, 1000), 1000)          # any value of π: it cancels
        c, G, M = Q(C.C_LIGHT), Q(rng.randrange(1, 10 ** 6), 10 ** 16), Q(rng.randrange(1, 10 ** 6))
        H = [Q(rng.randrange(1, 10 ** 9), 10 ** 27) for _ in range(5)]          # H(z) at five redshifts, any positive values
        a = [c * h / (2 * pi_) for h in H]
        v4 = [G * M * x for x in a]                                              # v⁴ = G M a₀ at fixed baryonic mass
        bad += any(a[k] / a[0] != H[k] / H[0] or v4[k] / v4[0] != H[k] / H[0] for k in range(5))
    R.check("D1", "in rational arithmetic, 300 random cases: with a₀(z) = cH(z)/2π and v⁴ = G M a₀ at fixed M, a₀(z)/a₀(0) = "
            "H(z)/H(0) and (v(z)/v(0))⁴ = H(z)/H(0) exactly at five redshifts, for any π, c, G, M and positive H(z)",
            bad == 0, f"{bad} failures", kind="CHART")
    # D2 floating point: E(z)^{1/4} in flat ΛCDM; at 32-dark's chart Ω_Λ = 0.7 the zero-point shifts +7 %, +15 %, +31 % at
    # z = 0.5, 1, 2 (32:P1); at the octant's Ω_Λ = 0.6837 it shifts +7 %, +16 %, +32 %; a constant floor shifts nothing
    s7 = [round(100 * (C.tully_fisher_shift(z, Q(7, 10)) - 1)) for z in (Q(1, 2), 1, 2)]
    so = [round(100 * (C.tully_fisher_shift(z, C.omega_lambda()) - 1)) for z in (Q(1, 2), 1, 2)]
    ok = s7 == [7, 15, 31] and so == [7, 16, 32]
    R.check("D2", "floating point: the Tully–Fisher zero-point E(z)^{1/4} − 1 at z = 0.5, 1, 2 is +7, +15, +31 % at Ω_Λ = 0.7 "
            "(32:P1's chart) and +7, +16, +32 % at the octant's Ω_Λ = tanh²(3π/8)", ok, f"Ω_Λ = 0.7: {s7}; octant: {so}", kind="CHART")


