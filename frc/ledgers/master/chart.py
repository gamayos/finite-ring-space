# block A: the floor (00:L1)
# a₀ = cH₀/2π at the channel-1 rate H₀ = 67.4 km s⁻¹ Mpc⁻¹: between 1.04 and 1.045 × 10⁻¹⁰ m s⁻², 13 % low against the
# fitted 1.20 × 10⁻¹⁰ and 0.7σ of its systematic 0.24 × 10⁻¹⁰ (Chart.lean: floor_value, floor_fine).
@R.block("A", BLOCKS["A"])
def block_A():
    """Block A — the floor (CHART): A1, A2."""
    # 00:L1 (p00084)
    a = C.floor_bracket()
    fit, err = C.A0_FIT
    ratio, deficit = (a[0] / fit, a[1] / fit), ((fit - a[1]) / err, (fit - a[0]) / err)
    ok = _inside(a, Q("1.04e-10"), Q("1.045e-10")) and _inside(ratio, Q("0.868"), Q("0.870")) and _inside(deficit, Q("0.65"), Q("0.67"))
    R.check("A1", "a₀ = cH₀/2π at the channel-1 rate H₀ = 67.4 km/s/Mpc, in rational arithmetic with π by Machin's formula: 1.04 < a₀/10⁻¹⁰ < 1.045; "
            "a₀ over the fitted 1.20 × 10⁻¹⁰ in (0.868, 0.870), 13 % low; the deficit over the systematic 0.24 × 10⁻¹⁰ in "
            "(0.65, 0.67), the row's 0.7σ", ok, f"a₀ in ({C.show(a[0], '.6e')}, {C.show(a[1], '.6e')}) m/s²", kind="CHART")
    # A2 floating point; and the floor at the landing H₀ of block B (67.35) rounds to the same 1.04 × 10⁻¹⁰
    a0, a0b = C.floor(), C.floor(C.hubble())
    ok = _near(a0, a[0], a[0] / 10 ** 12) and _near(a0b, Q("1.04e-10"), Q("0.005e-10")) and _near(C.sigma(a0, C.A0_FIT), Q("-0.66"), Q("0.01"))
    R.check("A2", "floating point: a₀ agrees with the rational bracket to 10⁻¹²; at the landing H₀ = 67.35 of the octant (00:L3) the floor is "
            "still 1.04 × 10⁻¹⁰; the deficit is −0.66σ", ok, f"a₀ = {a0:.5e}, at the landing {a0b:.5e}", kind="CHART")


# ------------------------------------------------------------------------------------------------------------
# block B: the octant record depth and its outputs (00:L3)
# the depth S/2 chronons is (π/4) r_H/c in the chart; Ω_Λ = tanh²(3π/8) = 0.684, 0.19σ from 0.685 ± 0.007; the locus
# t H₀ = (π/4)/tanh(3π/8) = 0.950; read on the stellar age 13.61 ± 0.34 Gyr it gives H₀ = 68.2 ± 1.7, the ladder's
# 73.0 ± 1.0 at 2.4σ; read on 13.79 Gyr the channel-1 67.4 (Chart.lean: octant_chart, landing_bracket, landing_fine,
# age_rate_locus, locus_bracket, octant_inversion, hubble_landing, hubble_stellar).
@R.block("B", BLOCKS["B"])
def block_B():
    """Block B — the octant record depth and its outputs (CHART): B1, B2."""
    # 00:L3 (p00181)
    rng = random.Random(30)
    conv = all((Q(S, 2) / (4 * S)) * 2 == Q(1, 4) for S in [rng.randrange(1, 10 ** 30) for _ in range(200)])   # (S/2)/(4S)·2π = π/4
    t, ol, loc = C.tanh_octant_bracket(), C.omega_lambda_bracket(), C.locus_bracket()
    h1, h0 = C.hubble_bracket(), C.hubble_bracket(C.STELLAR_AGE[0])
    err, pull = C.rate_error_bracket(), C.ladder_pull_bracket()
    dev = ((C.OMEGA_L_FIT[0] - ol[1]) / C.OMEGA_L_FIT[1], (C.OMEGA_L_FIT[0] - ol[0]) / C.OMEGA_L_FIT[1])
    ok = (conv and _inside(t, Q("0.82685"), Q("0.826851")) and _inside(ol, Q("0.68368"), Q("0.68369"))
          and _inside(dev, Q("0.186"), Q("0.19")) and _inside(loc, Q("0.949866"), Q("0.949868"))
          and _inside(h1, Q("67.35"), Q("67.36")) and _inside(h0, Q("68.24"), Q("68.25"))
          and _inside(err, Q("1.70"), Q("1.71")) and _inside(pull, Q("2.40"), Q("2.42")))
    R.check("B1", "in rational arithmetic (π by Machin, e^{3π/4} by its Taylor series with the tail bound): (S/2)/(4S) · 2π = π/4 "
            "for 200 random S; 0.82685 < tanh(3π/8) < 0.826851; 0.68368 < Ω_Λ = tanh²(3π/8) < 0.68369, between 0.186σ and 0.19σ "
            "below 0.685 ± 0.007; 0.949866 < (π/4)/tanh(3π/8) < 0.949868; on the stellar age 13.61 Gyr (Julian years) "
            "68.24 < H₀ < 68.25 km/s/Mpc, the age's ±0.34 carried to between 1.70 and 1.71, and the Cepheid ladder's "
            "73.0 ± 1.0 between 2.40σ and 2.42σ above it (errors combined with ±1.7); on 13.79 Gyr 67.35 < H₀ < 67.36",
            ok, f"Ω_Λ in ({C.show(ol[0], '.8f')}, {C.show(ol[1], '.8f')}); H₀ in ({C.show(h0[0], '.5f')}, {C.show(h0[1], '.5f')})", kind="CHART")
    # B2 floating point; the rival chart's identity lands on π/4 at Ω_Λ (the inversion, 14:C7) and the row's rounded numerals
    quarter = C.pi_bracket()[0] / 4
    age = C.lcdm_age(C.omega_lambda())
    hs = C.hubble(C.STELLAR_AGE[0])
    ok = (_near(C.omega_lambda(), ol[0], Q(1, 10 ** 12)) and _near(age, quarter, Q(1, 10 ** 12)) and _near(C.omega_lambda(), Q("0.684"), Q("0.0005"))
          and _near(hs, Q("68.2"), Q("0.05")) and _near(hs * C.STELLAR_AGE[1] / C.STELLAR_AGE[0], Q("1.7"), Q("0.05"))
          and _near(C.hubble(), Q("67.4"), Q("0.05")) and _near(C.sigma(C.omega_lambda(), C.OMEGA_L_FIT), Q("-0.19"), Q("0.005"))
          and _near(C.sigma(C.LADDER_FIT[0], (hs, (C.H0_ERR ** 2 + C.LADDER_FIT[1] ** 2) ** Q(1, 2))), Q("2.4"), Q("0.05")))
    R.check("B2", "floating point: Ω_Λ agrees with the rational bracket to 10⁻¹²; the rival chart's age (2/3) artanh √Ω_Λ equals π/4 there to "
            "10⁻¹²; the row's numerals: Ω_Λ = 0.684, −0.19σ, H₀ = 68.2 ± 1.7 on the stellar age, the ladder at 2.4σ from it, and "
            "the channel-1 67.4 on 13.79 Gyr", ok,
            f"Ω_Λ = {C.omega_lambda():.6f}, (2/3) artanh √Ω_Λ − π/4 = {C.show(age - quarter, '.1e')}, H₀ = {hs:.3f} on the stellar age", kind="CHART")


