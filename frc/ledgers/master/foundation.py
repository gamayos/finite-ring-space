    """Block F — the registered Universe is finite; the agent's bound (EXACT): F1–F4."""
    # 00:A2 (p00004)
    bad, det = [], []
    totalities = {"[0, 10^5)": range(10 ** 5), "the odd naturals below 2·10^5": range(1, 2 * 10 ** 5, 2),
                  "the squares below 10^10": (k * k for k in range(10 ** 5))}
    for name, members in totalities.items():
        members = list(members)
        for R_ in (1, 2, 7, 13, 233):
            readings = {"u mod R": lambda u, R_=R_: u % R_, "u mod R, squared": lambda u, R_=R_: (u * u) % R_,
                        "min(u, R−1)": lambda u, R_=R_: min(u, R_ - 1)}
            for rname, rho in readings.items():
                reg = _registered(rho, members)
                emb = [r % R_ for r in reg]                                   # the embedding into the shell of R points, by ofNat
                if not (len(reg) <= R_ and all(0 <= r < R_ for r in reg) and len(set(emb)) == len(reg)): bad.append((name, R_, rname, len(reg)))
                # among any R + 1 members two share a residue: the first R + 1 members, and R + 1 members spread out
                for sample in (members[:R_ + 1], members[::max(1, len(members) // (R_ + 1))][:R_ + 1]):
                    if len(sample) == R_ + 1 and _injective(lambda i, s=sample, rho=rho: rho(s[i]), R_ + 1): bad.append((name, R_, rname, "no collision"))
        det.append(f"{name}: under every reading into R ∈ {{1, 2, 7, 13, 233}} records the residues number ≤ R and embed in the shell of R points")
    R.check("F1", "three totalities of 10^5 members, three readings each into R ∈ {1, 2, 7, 13, 233} records: the registered Universe (the "
            "residues) has at most R members and embeds in the shell of R points; among any R + 1 members two share a residue",
            not bad, "; ".join(det) + f"; exceptions {bad[:3]}")
