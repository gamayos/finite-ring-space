# block V: mutual registration is one count (00:A3)
# injections both ways between shells force equal counts (the pigeonhole both ways; Foundation.lean,
# mutual_registration_count); a larger shell registers a smaller, so the theorem is silent on a host.
@R.block("V", BLOCKS["V"])
def block_V():
    """Block V — the registration is onto; mutual registration is one count (EXACT): V1–V3."""
    # 00:A3 (p00003)
    bad = []
    for m in range(1, SMALL + 1):
        for n in range(1, SMALL + 1):
            inj_mn = any(_injective(lambda x: f[x], m) for f in itertools.product(range(n), repeat=m))
            inj_nm = any(_injective(lambda x: g[x], n) for g in itertools.product(range(m), repeat=n))
            if (inj_mn and inj_nm) != (m == n) or inj_mn != (m <= n): bad.append((m, n))
    R.check("V1", f"every m, n ≤ {SMALL}: an injective reading of m members into n exists iff m ≤ n (exhaustive), so injections both "
            "ways exist iff m = n: two totalities each registered whole within the other have one count", not bad, f"exceptions {bad}")
    # V2 on the three Carriers: the Subject's p members are registered injectively in the Carrier (the identity), the Carrier's
    # Ω are not registered injectively in p states (a collision found by search): the larger shell hosts the smaller
    ok, det = True, []
    for Om, p in SHELLS:
        c = collision(lambda x: x % p, Om)
        ok &= _injective(lambda x: x, p) and c is not None and (c[0] % p) == (c[1] % p) and c[0] != c[1]
        det.append(f"Ω={Om}, p={p}: x ↦ x identifies no two of the p; x mod p identifies {c} of the Ω")
    R.check("V2", "on the three Carriers: the Subject is registered injectively within the Carrier and the Carrier is not within "
            "the Subject (collision by search): a larger shell registers a smaller, the theorem silent on a host", ok, "; ".join(det))
