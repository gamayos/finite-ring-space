    primes = _primes(3, SWEEP)
    bad = [p for p in primes if bool(quarter_turns(p)) != (p % 4 == 1)]
    built = [p for p in primes if p % 4 == 1 and quarter_turn(p) ** 2 % p != p - 1]
    R.check("H1", f"every odd prime p < {SWEEP}: x² = −1 has a root (by search) iff p ≡ 1 (mod 4); on p ≡ 1 (mod 4) the generator-free "
            "ħ = a^((p−1)/4) is one", not bad and not built, f"{len(primes)} primes; exceptions {bad + built}")
    # H2 the Carriers and their Subjects: ħ = a^S, ħ² = −1, and the two roots ±ħ
    ok, det = True, []
    for Om, p in SHELLS:
        for q in (Om, p):
            h = quarter_turn(q); a = half_power(q)
            ok &= q % 4 == 1 and pow(a, (q - 1) // 2, q) == q - 1 and h == pow(a, (q - 1) // 4, q) and h * h % q == q - 1
            if q < 10 ** 5: ok &= sorted(quarter_turns(q)) == sorted({h, q - h})
        det.append(f"Ω={Om}: ħ={quarter_turn(Om)}; p={p}: ħ={quarter_turn(p)}")
    R.check("H2", "on the three Carriers and their Subjects (all ≡ 1 mod 4): ħ = a^S with a^(2S) = −1 solves x² = −1, and below 10⁵ the "
            "roots are exactly ±ħ (by search)", ok, "; ".join(det))


