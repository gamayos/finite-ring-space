def _shells(lo, hi):
    return [n for n in range(lo, hi) if n % 4 == 1 and arith.is_prime(n)]


def near(x, y, rel=None, abs_=None):
    """|x − y| within the stated tolerance, the chart's float x read as a Fraction against rational bounds."""
    d = abs(Fraction(x) - Fraction(y))
    return (rel is not None and d <= Fraction(rel) * abs(Fraction(y))) or (abs_ is not None and d <= Fraction(abs_))


