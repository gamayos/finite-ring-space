SIZES = [1, 2, 3, 4]            # the random structures' sizes
FORMULAS = 600                  # random formulas per size
MAPS = 6                        # every map [0, n) → [0, n) for n ≤ MAPS

LEDGER = {"Q1": "00:Z1", "Q2": "00:Z1", "Q3": "00:Z1"}
BLOCKS = {"Q": "Gödel vacuous over a finite structure: no Q, the theory decided"}
