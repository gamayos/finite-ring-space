R = Registry("00", "logic", LEDGER, PREDICATES, sources=[__file__])


def _shell_structure(p):
    """The shell 𝔽_p as a relational structure: relation 0 the graph of the successor x ↦ x + 1, relation 1 the zero,
    relation 2 the graph of x ↦ 2x."""
    def rel(r, args):
        if r == 0: return len(args) == 2 and (args[0] + 1) % p == args[1]
        if r == 1: return len(args) == 1 and args[0] == 0
        if r == 2: return len(args) == 2 and 2 * args[0] % p == args[1]
        return False
    return p, rel


