def readout(m, g, n):
    """The framed readout of √m at scale n on the chart of generator g: s = ⌊√(m g^{2n})⌋, s² ≤ m g^{2n} < (s + 1)²,
    the registered value s / gⁿ (22-quantum, Def. readout)."""
    return isqrt(m * g ** (2 * n))


def largest_remainder(ps, B):
    """B counts allocated to the probabilities ps (Fractions summing to 1): the floors, then one count each to the
    largest remainders, ties by index."""
    prov = [int(B * q) for q in ps]
    rem = [B * q - v for q, v in zip(ps, prov)]
    counts = prov[:]
    for i in sorted(range(len(ps)), key=lambda i: (-rem[i], i))[:B - sum(prov)]: counts[i] += 1
    return counts


