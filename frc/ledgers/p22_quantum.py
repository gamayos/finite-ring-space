# ---- Gaussian integers as pairs, the ledger ℤ[i] of the suites -----------------------------------------------------
def gm(z, w): return (z[0] * w[0] - z[1] * w[1], z[0] * w[1] + z[1] * w[0])
def ga(z, w): return (z[0] + w[0], z[1] + w[1])
def gc(z): return (z[0], -z[1])
def gnorm(z): return z[0] * z[0] + z[1] * z[1]
I4 = [(1, 0), (0, 1), (-1, 0), (0, -1)]                       # i^l


def shell(p, e, nS, nO):
    """The Subject and Object cycles of orders nS, nO in F_p^x (generator e), their gcd and the core."""
    N = p - 1
    gS, gO = pow(e, N // nS, p), pow(e, N // nO, p)
    HS, HO = {pow(gS, j, p) for j in range(nS)}, [pow(gO, j, p) for j in range(nO)]
    return N, gS, gO, gcd(nS, nO), HS, HO, sorted(HS.intersection(HO))


