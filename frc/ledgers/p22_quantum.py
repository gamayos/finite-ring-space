# block S: the Sorkin hierarchy (sorkin.py, 22:C8, P2, X8)
# Four slits carry deterministic Gaussian-integer components on the Object cycle. The k-th order Sorkin combination is
# taken over every channel and outcome, on F_157 and F_421. I2 is nonzero, and I3 = I4 = 0 exactly. The observed
# combination comes from the lifted shadows. It is zero below the horizon, where every tally is below p. Above the
# horizon it is a multiple of p, with nonzero instances.
@R.block("S", BLOCK["S"])
def block_S():
    """Block S — sorkin.py (EXACT): S1–S3, the package's 8 checks."""
    cnt = [0]
    def nxt():
        cnt[0] += 1; return cnt[0]
    wide = lambda: (((nxt() * 5) % 19) - 9, ((nxt() * 13) % 19) - 9)
    binary = lambda: (nxt() % 2, 0)
    deep = lambda: (7 * (((nxt() * 5) % 19) - 9), 7 * (((nxt() * 13) % 19) - 9))
    def run(p, e, nO, nslits, coeff):
        gO = pow(e, (p - 1) // nO, p); HO = [pow(gO, j, p) for j in range(nO)]; q = nO // 4
        slits = [{u: coeff() for u in HO} for _ in range(nslits)]
        W = {}
        for mask in range(1, 1 << nslits):
            S = tuple(i for i in range(nslits) if mask >> i & 1)
            for r in range(4):
                for a in range(q):
                    s = (0, 0)
                    for l in range(4):
                        u = pow(gO, a + q * l, p); comp = (0, 0)
                        for i in S: comp = ga(comp, slits[i][u])
                        s = ga(s, gm(gc(I4[(r * l) % 4]), comp))
                    W[(S, r, a)] = gnorm(s)
        return W, q
    def hier(W, q, k, lift=None):
        out = []
        for r in range(4):
            for a in range(q):
                out.append(sum((-1) ** (k - m) * (W[(c, r, a)] if lift is None else W[(c, r, a)] % lift)
                               for m in range(1, k + 1) for c in combinations(range(k), m)))
        return out
    ok = True; det = []
    for p, e, nO, tag in [(157, 5, 12, "157/53/13"), (421, 2, 28, "421/61/29")]:
        W, q = run(p, e, nO, 4, wide)
        I2, I3, I4v = hier(W, q, 2), hier(W, q, 3), hier(W, q, 4)
        ok &= any(I2) and not any(I3) and not any(I4v)
        det.append(f"{tag}: max |I2| = {max(map(abs, I2))}")
    # 22:C8 (p22024), 22:X8 (p22051)
    R.check("S1", "Sorkin nullity on F_157 and F_421: I2 generically nonzero, I3 = I4 = 0 exactly on every channel and outcome", ok, "; ".join(det))

    p = 157
    W, q = run(p, 5, 12, 3, binary)
    I3h = hier(W, q, 3, p)
