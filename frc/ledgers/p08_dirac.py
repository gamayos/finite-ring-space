def _factor(n):
    f, d = {}, 2
    while d * d <= n:
        while n % d == 0: f[d] = f.get(d, 0) + 1; n //= d
        d += 1
    if n > 1: f[n] = f.get(n, 0) + 1
    return f


def _mpow(K, U, e):
    R, X = ident(len(U)), U
    while e:
        if e & 1: R = mmul(K, R, X)
        e >>= 1
        if e: X = mmul(K, X, X)
    return R


def _korder(K, p, A, d, cap):
    X, k = A, 1
    while not keq(K, X, kid(d)):
        X = kconv(K, p, X, A); k += 1
        if k > cap: return None
    return k


