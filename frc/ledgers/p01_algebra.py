# block C: the orbital complex and its poles (Section 4)
@R.block("C", BLOCK["C"])
def block_C():
    """Block C — the orbital complex and its poles (EXACT): C1–C3."""
    ok, det = True, []
    for p in MID:
        k = AL.kappa(p); g = G; n2 = 2 * k
        M = lambda n, a: a * pow(g, n, p) % p
        L = lambda a, m: a * pow(g, m, p) % p
        ok &= all(M(n, a) == M(n + n2, (-a) % p) for n in range(p - 1) for a in range(p))
        ok &= all(L(a, m) == L((-a) % p, m + n2) for a in range(1, p) for m in range(p - 1))
        ok &= len({pow(g, n, p) for n in range(p - 1)}) == p - 1                    # the p − 1 meridian steps are distinct
        circles = {frozenset({pow(g, n, p), pow(g, n + n2, p)}) for n in range(p - 1)}
        ok &= len(circles) == n2
        pairs = {}
        for a in range(1, n2 + 1):
            for x in (a % p, (-a) % p):
                ok &= x not in pairs; pairs[x] = a                                    # every nonzero residue is ±a once
        ok &= sorted(pairs) == list(range(1, p))
        ok &= (p - 1) ** 2 == 2 * (n2 * (p - 1))
        det.append(f"p={p}: {p-1} meridian steps, {len(circles)} great circles, {n2} sign pairs, |V| = {n2 * (p - 1) + 1}")
    # 1:C4 (p01011)
    R.check("C1", "M_n(a) = M_{n+2κ}(−a), L_a(m) = L_{−a}(m+2κ); p − 1 distinct meridian steps in 2κ great circles; 2κ sign pairs {±a}, a ≤ 2κ; |V| = (p − 1)²/2 + 1",
            ok, "; ".join(det))
    ok = all([s for s in range(p) if 2 * s % p == 0] == [0] for p in primes(3, 400))
    ok &= all(2 * (2 * AL.kappa(p) + 1) % p == 1 for p in SUBJECTS)
    # 1:Z1 (p01020)
    R.check("C2", "2s = 0 forces s = 0 on every odd prime below 400; on the shell 2⁻¹ = 2κ + 1, the residue just past the antipode p/2", ok,
            "odd primes 3..397; the Subjects")
    ok, det = True, []
