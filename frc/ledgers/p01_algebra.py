        k = AL.kappa(p); inv4 = pow(4, -1, p)
        ok &= [s for s in range(p) if 4 * s % p == 0] == [0]
        ok &= Fraction(p, 4) == k + Fraction(1, 4) and k % p == (-inv4) % p and (k + 1) % p == 3 * inv4 % p
